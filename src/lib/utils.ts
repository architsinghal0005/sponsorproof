import { type ClassValue, clsx } from "clsx";
import { twMerge } from "tailwind-merge";
import type { CampaignReport } from "./types.ts";

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

/**
 * Converts a CampaignReport into a clean, presentation-ready Markdown string
 */
export function generateMarkdownReport(report: CampaignReport): string {
  const dateStr = new Date(report.timestamp).toLocaleString();

  let md = `# SponsorProof Audit Report: ${report.campaignName}\n\n`;
  md += `**Date:** ${dateStr}  \n`;
  md += `**Deliverable Type:** ${report.deliverableType}  \n`;
  md += `**Compliance Score:** ${report.overallScore}/100 (${report.complianceStatus.replace(/_/g, " ")})  \n`;
  md += `**Analysis Engine:** ${report.executionMeta.modelUsed} (${report.executionMeta.analysisMode})  \n\n`;

  md += `## Executive Summary\n${report.summary}\n\n`;

  md += `## Score & Breakdown\n`;
  md += `- **Pass:** ${report.counts.pass}\n`;
  md += `- **Missing:** ${report.counts.missing}\n`;
  md += `- **Needs Review:** ${report.counts.needsReview}\n`;
  md += `- **Total Checked:** ${report.counts.total}\n\n`;

  md += `## Spoken & Word Count Metrics\n`;
  md += `- Content Words: ${report.sourceStats.contentWordCount}\n`;
  md += `- Estimated Speaking Duration (~140 wpm): ${report.sourceStats.estimatedSpeakingTimeFormatted}\n\n`;

  md += `## Detailed Evidence Findings\n\n`;

  for (const f of report.findings) {
    const statusEmoji =
      f.status === "PASS" ? "✅ PASS" : f.status === "MISSING" ? "❌ MISSING" : "⚠️ NEEDS REVIEW";

    md += `### [${statusEmoji}] ${f.title}\n`;
    md += `- **Category:** ${f.category}\n`;
    md += `- **Severity:** ${f.severity}\n`;
    md += `- **Source:** ${f.sourceType.toUpperCase()}\n\n`;

    if (f.briefQuote?.text) {
      md += `> **Brief Requirement Quote** (${f.briefQuote.verified ? "Verified" : "Unverified"}):\n`;
      md += `> "${f.briefQuote.text}"\n\n`;
    }

    if (f.contentQuote?.text) {
      md += `> **Content Quote** (${f.contentQuote.verified ? "Verified" : "Unverified"}):\n`;
      md += `> "${f.contentQuote.text}"\n\n`;
    } else if (f.status === "MISSING") {
      md += `> *Not found in submitted content.*\n\n`;
    }

    md += `**Explanation:** ${f.explanation}\n\n`;

    if (f.suggestedFix) {
      md += `**Suggested Fix:**\n\`\`\`\n${f.suggestedFix}\n\`\`\`\n\n`;
    }

    md += `---\n\n`;
  }

  md += `\n*Generated by SponsorProof - Evidence-Based Sponsored Content Verification*\n`;
  return md;
}
